def by_id(recipe_id: str) -> Recipe | None:
    for recipe in RECIPES:
        if recipe.id == recipe_id:
            return recipe
    return None


def available_gear(has_multi: bool) -> set[str]:
    gear = {"airfryer", "pan", "pot", "microwave"}
    if has_multi:
        gear.add("multi")
    return gear


def choose_recipe(
    day: date,
    *,
    has_multi: bool = False,
    avoid: list[str] | None = None,
    prefer: str | None = None,
    shift: int = 0,
) -> Recipe:
    gear = available_gear(has_multi)
    pool = [recipe for recipe in RECIPES if recipe.minutes <= 15 and set(recipe.gear) <= gear]
    if prefer:
        narrowed = [recipe for recipe in pool if prefer in recipe.gear]
        if narrowed:
            pool = narrowed
    skipped = set(avoid or [])
    fresh = [recipe for recipe in pool if recipe.id not in skipped]
    use = sorted(fresh or pool, key=lambda recipe: recipe.id)
    index = (day.toordinal() + shift) % len(use)
    return use[index]
