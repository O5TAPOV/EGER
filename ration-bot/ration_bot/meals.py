def metabolism(kg: float) -> dict[str, int]:
    bmr = 10 * kg + 6.25 * HEIGHT_CM - 5 * AGE_YEARS + 5
    burn = round(bmr * ACTIVITY)
    goal = max(KCAL_FLOOR, burn - DEFICIT)
    return {"burn": burn, "goal": goal, "deficit": burn - goal}


def budget_line(kg: float) -> str:
    row = metabolism(kg)
    return (
        f"🎯 На {kg:.1f} кг при 185 см витрата ~{row['burn']} ккал. "
        f"Їж близько {row['goal']} ккал. Мінус {row['deficit']} ккал від витрати, "
        f"це десь пів кіло жиру на тиждень, спокійно і без голодовки."
    )


def stem(word: str) -> str:
    text = word.casefold().replace("ї", "і").strip()
    for suffix in ("ами", "ями", "ів", "ей", "ою", "ям", "ях", "и", "і", "а", "я", "у", "ю"):
        if len(text) > 4 and text.endswith(suffix):
            return text[: -len(suffix)]
    return text


def _same_food(left: str, right: str) -> bool:
    if not left or not right:
        return False
    return left.startswith(right) or right.startswith(left)


def blocked(dish: Dish, hates: list[str]) -> bool:
    stems = [stem(item) for item in hates if stem(item)]
    for ingredient in dish.ingredients:
        ingredient_stem = stem(ingredient)
        for hate in stems:
            if _same_food(hate, ingredient_stem):
                return True
    return False


def options(slot: str, hates: list[str]) -> list[Dish]:
    found = [dish for dish in DISHES if dish.slot == slot and not blocked(dish, hates)]
    if found:
        return sorted(found, key=lambda dish: dish.id)
    return sorted((dish for dish in DISHES if dish.slot == slot), key=lambda dish: dish.id)[:1]


def pick(slot: str, day: date, hates: list[str], *, shift: int = 0, avoid: set[str] | None = None) -> Dish:
    pool = options(slot, hates)
    fresh = [dish for dish in pool if dish.id not in (avoid or set())]
    use = fresh or pool
    index = (day.toordinal() + shift) % len(use)
    return use[index]


def day_menu(day: date, hates: list[str], *, shifts: dict[str, int] | None = None) -> dict[str, Dish]:
    shifts = shifts or {}
    menu: dict[str, Dish] = {}
    used: set[str] = set()
    for slot in SLOTS:
        dish = pick(slot, day, hates, shift=shifts.get(slot, 0), avoid=used)
        menu[slot] = dish
        used.add(dish.id)
    return menu


def _fillers(gap: int) -> str:
    left = gap
    parts: list[str] = []
    parts.append(f"200 г творогу 5% (~{TVOROG_SNACK_KCAL} ккал, Б 34 · Ж 10 · В 4)")
    left -= TVOROG_SNACK_KCAL
    buckwheat_blocks = 0
    while left > 120 and buckwheat_blocks < 2:
        buckwheat_blocks += 1
        left -= BUCKWHEAT_70_KCAL
    if buckwheat_blocks:
        grams = 70 * buckwheat_blocks
        parts.append(f"гречка суха {grams} г (~{BUCKWHEAT_70_KCAL * buckwheat_blocks} ккал)")
    if left > 120:
        parts.append(f"2 яйця (~{TWO_EGGS_KCAL} ккал)")
    listed = "\n".join(f"• {part}" for part in parts)
    return (
        f"➕ До норми ще ~{gap} ккал. Три тарілки самі по собі це дірка, з неї ввечері і зриває на солодке. Добери і зупинись:\n"
        f"{listed}"
    )


def render_dish(slot: str, dish: Dish, *, kg: float | None = None) -> str:
    lines = [
        f"{SLOT_EMOJI[slot]} {SLOT_TITLES[slot]}: {dish.title}",
        f"📊 БЖУ: {dish.kcal} ккал · Б {dish.protein} г · Ж {dish.fat} г · В {dish.carbs} г",
    ]
    if dish.fat_label:
        lines.append(f"🏷 {dish.fat_label}")
    lines.append(f"⏱ Руками {dish.minutes} хв.")
    lines.extend(f"{index}. {step}" for index, step in enumerate(dish.steps, start=1))
    if kg is not None:
        goal = metabolism(kg)["goal"]
        lines.append(f"🎯 Норма на день ~{goal} ккал. Попереду ще інші прийоми.")
    return "\n".join(lines)


def render_menu(menu: dict[str, Dish], hates: list[str], kg: float = 111.6) -> str:
    kcal = sum(dish.kcal for dish in menu.values())
    protein = sum(dish.protein for dish in menu.values())
    fat = sum(dish.fat for dish in menu.values())
    carbs = sum(dish.carbs for dish in menu.values())
    lines = ["🍽 Твій день, одна порція.", budget_line(kg)]
    if hates:
        lines.append("🚫 Без: " + ", ".join(hates) + ".")
    lines.append(f"📊 Разом по тарілках: {kcal} ккал · Б {protein} г · Ж {fat} г · В {carbs} г.")
    gap = metabolism(kg)["goal"] - kcal
    if gap > 150:
        lines.append(_fillers(gap))
    elif gap < -200:
        lines.append("✅ Норму вже закрито. Другу вечерю зверху не ліпи.")
    else:
        lines.append("✅ Ти в коридорі норми. Зверху ще одну тарілку не клади.")
    lines.append("")
    for slot in SLOTS:
        lines.append(render_dish(slot, menu[slot]))
        lines.append("")
    lines.append("Інша страва: /next lunch. Прибрати продукт: /hate гриби")
    return "\n".join(lines).strip()


def shopping(menu: dict[str, Dish]) -> list[str]:
    items: list[str] = []
    seen: set[str] = set()
    for slot in SLOTS:
        for item in menu[slot].shop:
            if item.casefold() not in seen:
                seen.add(item.casefold())
                items.append(item)
    return items
